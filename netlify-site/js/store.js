window.getKashoriaProducts = function() {
  const base = Array.isArray(window.KASHORIA_PRODUCTS) ? window.KASHORIA_PRODUCTS : [];
  let custom = [];
  try {
    custom = JSON.parse(localStorage.getItem("kashoria_products") || "[]");
  } catch (_) {
    custom = [];
  }

  // Never let an old/broken admin record replace a real catalog product.
  const isUsable = p => {
    if (!p || !p.id || !p.name || !p.image) return false;
    const price = Number(p.price);
    if (!Number.isFinite(price) || price <= 0) return false;
    const image = String(p.image).toLowerCase();
    if (image.includes("placeholder") || image.endsWith("logo.png")) return false;
    return true;
  };

  const map = new Map();
  base.filter(isUsable).forEach(p => map.set(p.id, p));
  custom.filter(isUsable).forEach(p => map.set(p.id, p));
  return [...map.values()];
};

